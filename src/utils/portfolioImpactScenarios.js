const finite = (value) => typeof value === "number" && Number.isFinite(value);
const date = (value) =>
  typeof value === "string" &&
  /^\d{4}-\d{2}-\d{2}$/.test(value) &&
  Number.isFinite(Date.parse(value)) &&
  new Date(value).toISOString().slice(0, 10) === value;
const ratio = (a, b, factor = 100) =>
  b > 0 && finite((a / b) * factor) ? (a / b) * factor : null;
const median = (values) => {
  const sorted = values.filter(finite).sort((a, b) => a - b),
    n = sorted.length;
  return n
    ? n % 2
      ? sorted[(n - 1) / 2]
      : sorted[n / 2 - 1] / 2 + sorted[n / 2] / 2
    : null;
};
const strictNumber = (value) =>
  (typeof value === "number" ||
    (typeof value === "string" &&
      value.trim() &&
      /^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:e[+-]?\d+)?$/i.test(value.trim()))) &&
  Number.isFinite(Number(value))
    ? Number(value)
    : null;

/** Validate the actual filing registrant and accession separately: filing agents can have a different accession prefix. */
function sourceValid(source, company, today) {
  if (
    !source ||
    !date(source.filed) ||
    source.filed > today ||
    !date(source.end) ||
    source.end > source.filed ||
    (source.start != null &&
      (!date(source.start) || source.start > source.end)) ||
    source.unit !== "USD" ||
    !finite(source.value) ||
    !/^[A-Za-z0-9_-]+$/.test(source.tag || "") ||
    !/^\d{10}-\d{2}-\d{6}$/.test(source.accession || "")
  )
    return false;
  try {
    const url = new URL(source.documentUrl || source.url);
    const match = url.pathname.match(
      /^\/Archives\/edgar\/data\/(\d{1,10})\/(\d{18})\/(?:[^/]+)?$/,
    );
    if (
      url.protocol !== "https:" ||
      url.username ||
      url.password ||
      url.port ||
      url.search ||
      url.hash ||
      !["sec.gov", "www.sec.gov", "data.sec.gov"].includes(url.hostname) ||
      !match ||
      match[2] !== source.accession.replaceAll("-", "")
    )
      return false;
    const cik = match[1].padStart(10, "0"),
      continuity = company.evidenceContinuity;
    const related =
      cik === company.cik ||
      (source.sourceCik === cik &&
        continuity?.currentCik === company.cik &&
        continuity?.predecessorCiks?.includes(cik) &&
        continuity?.factSourceCiks?.includes(cik));
    return related && (!source.sourceCik || source.sourceCik === cik);
  } catch {
    return false;
  }
}

const DIFFERENCE_FORMULA = "Current cumulative value − prior cumulative value";
const TTM_FORMULA = "Sum of four consecutive standalone quarters";
const nextDay = (value) =>
  new Date(Date.parse(value) + 86400000).toISOString().slice(0, 10);
const days = (start, end) =>
  (Date.parse(end) - Date.parse(start)) / 86400000 + 1;
const arithmeticEqual = (a, b, inputs = []) =>
  finite(a) &&
  finite(b) &&
  Math.abs(a - b) <=
    Math.max(1, Math.abs(a), Math.abs(b), ...inputs.map(Math.abs)) *
      Number.EPSILON *
      16;

/** Recompute the two raw-flow derivations emitted by xbrlPeriods; formula text is never evaluated as code. */
function derivedValueValid(point) {
  const { sources, observationPeriod: observation } = point;
  const formula = typeof point.formula === "string" ? point.formula : "";
  if (
    observation.kind !== "duration" ||
    ![DIFFERENCE_FORMULA, TTM_FORMULA].includes(formula) ||
    new Set(
      sources.map(
        (source) => `${source.taxonomy}|${source.tag}|${source.unit}`,
      ),
    ).size !== 1
  )
    return false;
  const differenceValid = (value, start, end) => {
    if (
      !date(start) ||
      !date(end) ||
      days(start, end) < 60 ||
      days(start, end) > 120 ||
      !finite(value)
    )
      return false;
    return sources.some(
      (current) =>
        current.end === end &&
        current.start < start &&
        days(current.start, end) > 120 &&
        days(current.start, end) <= 400 &&
        sources.some(
          (prior) =>
            prior.start === current.start &&
            nextDay(prior.end) === start &&
            prior.filed <= current.filed &&
            arithmeticEqual(current.value - prior.value, value, [
              current.value,
              prior.value,
            ]),
        ),
    );
  };
  if (formula === DIFFERENCE_FORMULA)
    return (
      point.period.kind === "quarter" &&
      differenceValid(point.value, observation.start, observation.end)
    );
  if (
    point.period.kind !== "ttm" ||
    days(observation.start, observation.end) < 300 ||
    days(observation.start, observation.end) > 400
  )
    return false;
  const intermediates = (
    Array.isArray(point.calculations) ? point.calculations : []
  ).filter((item) => item?.formula === DIFFERENCE_FORMULA);
  if (
    intermediates.some(
      (item) =>
        (item.unit && item.unit !== point.unit) ||
        !differenceValid(item.value, item.start, item.end),
    )
  )
    return false;
  const candidates = [
    ...sources.filter(
      (source) =>
        source.start &&
        days(source.start, source.end) >= 60 &&
        days(source.start, source.end) <= 120,
    ),
    ...intermediates,
  ].filter(
    (item) => item.start >= observation.start && item.end <= observation.end,
  );
  const unique = [
    ...new Map(
      candidates.map((item) => [
        `${item.start}|${item.end}|${item.value}`,
        item,
      ]),
    ).values(),
  ];
  const paths = (start, count, amounts) => {
    if (count === 4)
      return (
        start === nextDay(observation.end) &&
        arithmeticEqual(
          amounts.reduce((sum, value) => sum + value, 0),
          point.value,
          amounts,
        )
      );
    return unique.some(
      (item) =>
        item.start === start &&
        paths(nextDay(item.end), count + 1, [...amounts, item.value]),
    );
  };
  return paths(observation.start, 0, []);
}

function metric(company, key, kind, today) {
  const definition = portfolioMetricDefinitionFor(key),
    point = company?.metrics?.[key];
  if (portfolioMetricState(company, definition) !== "available")
    return {
      reason: `${definition?.label || key} is unavailable on a supported USD reporting basis.`,
    };
  if (!portfolioPeriodKey(point.period) || point.period.end > today)
    return {
      reason: `${definition.label} has an invalid or future reporting period.`,
    };
  const observation = point.observationPeriod;
  if (
    !observation ||
    observation.kind !== kind ||
    observation.end !== point.period.end ||
    (kind === "duration" && observation.start !== point.period.start) ||
    (kind === "instant" && observation.start != null)
  )
    return {
      reason: `${definition.label} does not have a compatible ${kind === "instant" ? "ending balance" : "full reporting duration"}.`,
    };
  if (
    !Array.isArray(point.sources) ||
    !point.sources.length ||
    point.sources.some((source) => !sourceValid(source, company, today))
  )
    return {
      reason: `${definition.label} lacks verified issuer filing evidence.`,
    };
  if (
    point.period.asOf &&
    (!date(point.period.asOf) ||
      point.period.asOf > today ||
      point.sources.some((source) => source.filed > point.period.asOf))
  )
    return {
      reason: `${definition.label} contains evidence outside its selected filing-date cutoff.`,
    };
  if (
    point.classification === "reported" &&
    !point.sources.some(
      (source) =>
        source.end === observation.end &&
        (source.start || null) === (observation.start || null) &&
        source.value === point.value,
    )
  )
    return {
      reason: `${definition.label} does not match its reported source value and observation dates.`,
    };
  if (point.classification !== "reported" && !derivedValueValid(point))
    return {
      reason: `${definition.label} cannot be reconciled to a supported calculation from its captured SEC inputs.`,
    };
  const calculations = [
    ...(Array.isArray(point.calculations) ? point.calculations : []),
  ];
  if (
    point.formula &&
    !calculations.some(
      (item) =>
        item?.formula === point.formula &&
        item?.value === point.value &&
        item?.start === observation.start &&
        item?.end === observation.end,
    )
  )
    calculations.push({
      formula: point.formula,
      value: point.value,
      start: observation.start,
      end: observation.end,
      unit: point.unit,
    });
  return {
    point,
    evidence: {
      key,
      label: definition.label,
      value: point.value,
      unit: point.unit,
      period: { ...point.period },
      observationPeriod: { ...observation },
      classification: point.classification,
      formula: point.formula || null,
      calculationVerification:
        point.classification === "reported"
          ? "Matches reported source value and observation dates"
          : "Recomputed from captured SEC inputs",
      calculations,
      sources: point.sources.map((source) => {
        const url = source.documentUrl || source.url,
          index = new URL(url).pathname.endsWith("/");
        return {
          ...source,
          url,
          linkKind: index ? "filing-index" : "filing-document",
          linkLabel: index ? "SEC filing index" : "SEC filing",
        };
      }),
    },
  };
}

function calculate(category, values, inputs) {
  if (category === "operating") {
    const [revenue, income] = values,
      costs = revenue - income,
      g = inputs.revenuePct / 100,
      v = inputs.variableCostPct / 100,
      c = inputs.costPct / 100;
    if (!(revenue > 0) || !(costs >= 0) || !finite(costs))
      return {
        reason:
          "The operating model requires positive revenue and nonnegative implied operating costs.",
      };
    const modeledRevenue = revenue * (1 + g),
      volumeCosts = costs * (1 + v * g);
    if (![modeledRevenue, volumeCosts, volumeCosts * (1 + c)].every(finite))
      return {
        reason:
          "These operating assumptions exceed the supported numerical range.",
      };
    const components = [
      { id: "revenue", label: "Revenue change", value: revenue * g },
      {
        id: "volumeCosts",
        label: "Volume-linked cost change",
        value: -costs * v * g,
      },
      {
        id: "costChange",
        label: "Operating cost change",
        value: -volumeCosts * c,
      },
    ];
    const change = components.reduce((sum, item) => sum + item.value, 0),
      modeled = income + change;
    return {
      baseline: income,
      modeled,
      change,
      impactPct: ratio(change, revenue),
      beforeRatio: ratio(income, revenue),
      afterRatio: ratio(modeled, modeledRevenue),
      components,
      modeledRevenue,
      modeledCosts: volumeCosts * (1 + c),
      baselineCosts: costs,
    };
  }
  if (category === "cash") {
    const [ocf, capex] = values;
    if (!ocf || capex < 0)
      return {
        reason:
          "The cash sensitivity requires nonzero operating cash flow and nonnegative reported PP&E purchases.",
      };
    const change = (Math.abs(ocf) * inputs.cashFlowPct) / 100,
      baseline = ocf - capex,
      modeledOcf = ocf + change;
    return {
      baseline,
      modeled: baseline + change,
      change,
      impactPct: ratio(change, Math.abs(ocf)),
      beforeRatio: ratio(ocf, capex, 1),
      afterRatio: ratio(modeledOcf, capex, 1),
      components: [
        { id: "cashFlow", label: "Operating cash flow change", value: change },
      ],
      modeledCashFlow: modeledOcf,
      capex,
    };
  }
  const [assets, equity, cash] = values;
  if (!(assets > 0) || (finite(cash) && (cash < 0 || cash > assets)))
    return {
      reason:
        "The balance sensitivity requires positive assets and compatible nonnegative cash no greater than assets.",
    };
  const loss = (assets * inputs.assetLossPct) / 100;
  if (
    finite(cash) &&
    loss > assets - cash + Math.max(assets, cash) * Number.EPSILON * 16
  )
    return {
      reason:
        "The assumed noncash asset loss exceeds reported assets less cash.",
    };
  const modeledAssets = assets - loss;
  if (!(modeledAssets > 0))
    return { reason: "The assumed loss leaves no positive asset base." };
  return {
    baseline: equity,
    modeled: equity - loss,
    change: -loss,
    impactPct: ratio(-loss, equity),
    beforeRatio: ratio(equity, assets),
    afterRatio: ratio(equity - loss, modeledAssets),
    components: [
      { id: "assetLoss", label: "New noncash asset loss", value: -loss },
    ],
    modeledAssets,
    noncashCapacityVerified: finite(cash),
  };
}

