/** Company sensitivities are independent of allocation. Weights annotate coverage only when complete and reviewed. */
export function buildPortfolioImpactScenarios(report, companies, options = {}) {
  const scenario =
    IMPACT_SCENARIOS.find(
      (item) => item.id === (options.scenarioId || "demand"),
    ) || IMPACT_SCENARIOS[0];
  const errors = [],
    inputs = {};
  if (
    options.scenarioId &&
    !IMPACT_SCENARIOS.some((item) => item.id === options.scenarioId)
  )
    errors.push("Choose an available scenario.");
  for (const item of scenario.controls) {
    const value =
      options[item.key] === undefined
        ? scenario.defaults[item.key]
        : strictNumber(options[item.key]);
    if (value === null || value < item.min || value > item.max)
      errors.push(
        `${item.label} must be a number from ${item.min} to ${item.max}.`,
      );
    inputs[item.key] = value;
  }
  const now = options.now ?? Date.now(),
    time = new Date(now).getTime();
  const today = finite(time) ? new Date(time).toISOString().slice(0, 10) : null;
  if (!today) errors.push("The calculation date is invalid.");
  const scope = options.scope || "all",
    targetCik = canonicalPortfolioCik(options.targetCik),
    targetSector =
      typeof options.targetSector === "string" ? options.targetSector : "";
  if (!["all", "company", "sector"].includes(scope))
    errors.push("Choose all companies, one company, or one sector.");
  const byCik = new Map(),
    ambiguous = new Set();
  for (const company of Array.isArray(companies) ? companies : []) {
    const cik = canonicalPortfolioCik(company?.cik);
    if (!cik) continue;
    if (byCik.has(cik)) ambiguous.add(cik);
    else byCik.set(cik, company);
  }
  const issuers = [
    ...new Map(
      (report?.concentration?.issuers || [])
        .filter((item) => canonicalPortfolioCik(item.cik))
        .map((item) => [
          canonicalPortfolioCik(item.cik),
          {
            ...item,
            cik: canonicalPortfolioCik(item.cik),
            sector: item.sector || "Unclassified",
          },
        ]),
    ).values(),
  ];
  if (scope === "company" && !issuers.some((item) => item.cik === targetCik))
    errors.push("Choose a company in this research list.");
  if (
    scope === "sector" &&
    (!targetSector || !issuers.some((item) => item.sector === targetSector))
  )
    errors.push("Choose a sector in this research list.");
  const selected = issuers.filter((item) =>
    scope === "company"
      ? item.cik === targetCik
      : scope === "sector"
        ? item.sector === targetSector
        : true,
  );
  const weighted =
    report?.weighted === true &&
    report?.concentration?.complete === true &&
    !(report?.unresolvedCount > 0) &&
    issuers.every(
      (item) =>
        item.weightComplete && finite(item.weightPct) && item.weightPct >= 0,
    ) &&
    Math.abs(issuers.reduce((sum, item) => sum + item.weightPct, 0) - 100) <=
      1e-6;
  const exclusions = [],
    rows = [];
  let eligibleCount = 0;
  for (const issuer of selected) {
    const company = byCik.get(issuer.cik),
      identity = {
        cik: issuer.cik,
        rowId: issuer.rowIds?.[0] || "",
        name: issuer.name || company?.name || issuer.cik,
        ticker: (issuer.tickers || []).join(" / ") || company?.ticker || "",
        sector: issuer.sector || "Unclassified",
        weightPct: weighted ? issuer.weightPct : null,
      };
    const applicable =
      issuer.kind !== "fund" &&
      (scenario.category === "balance" || company?.lens === "corporate");
    const exclude = (reason, code = "evidence") =>
      exclusions.push({ ...identity, reason, code, applicable });
    if (!applicable) {
      exclude(
        issuer.kind === "fund"
          ? "Fund look-through financials are not modeled."
          : "This operating-company sensitivity does not apply to financial institutions or an unclassified business model.",
        "not-applicable",
      );
      continue;
    }
    eligibleCount++;
    if (errors.length) {
      exclude(
        "Complete valid scenario inputs to calculate this company.",
        "inputs",
      );
      continue;
    }
    if (ambiguous.has(issuer.cik)) {
      exclude(
        "Conflicting company snapshots share this issuer identity.",
        "identity",
      );
      continue;
    }
    if (!companyAvailable(company)) {
      exclude("Supported captured company financial evidence is unavailable.");
      continue;
    }
    const keys =
      scenario.category === "operating"
        ? ["revenue", "operatingIncome"]
        : scenario.category === "cash"
          ? ["operatingCashFlow", "capex"]
          : ["totalAssets", "stockholdersEquity"];
    const kind = scenario.category === "balance" ? "instant" : "duration";
    const checked = keys.map((key) => metric(company, key, kind, today));
    if (checked.some((item) => item.reason)) {
      exclude(checked.find((item) => item.reason).reason);
      continue;
    }
    if (
      new Set(checked.map((item) => portfolioPeriodKey(item.point.period)))
        .size !== 1
    ) {
      exclude(
        "Financial inputs have different full reporting periods.",
        "period",
      );
      continue;
    }
    const evidence = checked.map((item) => item.evidence),
      values = checked.map((item) => item.point.value);
    if (scenario.category === "balance") {
      const cash = metric(company, "cash", "instant", today);
      if (
        !cash.reason &&
        portfolioPeriodKey(cash.point.period) ===
          portfolioPeriodKey(checked[0].point.period)
      ) {
        values.push(cash.point.value);
        evidence.push(cash.evidence);
      }
    }
    const result = calculate(scenario.category, values, inputs);
    if (
      result.reason ||
      ![
        result.baseline,
        result.modeled,
        result.change,
        ...result.components.map((item) => item.value),
      ].every(finite)
    ) {
      exclude(
        result.reason || "These values exceed the supported numerical range.",
        "model",
      );
      continue;
    }
    const primary = scenario.controls[0],
      span =
        primary.key === "assetLossPct" ? 2 : primary.key === "costPct" ? 5 : 10;
    const shocks = [
      ...new Set([
        primary.min,
        ...[-2, -1, 0, 1, 2].map((n) =>
          Math.max(
            primary.min,
            Math.min(primary.max, inputs[primary.key] + span * n),
          ),
        ),
        primary.max,
      ]),
    ].sort((a, b) => a - b);
    const sensitivity = shocks.map((shock) => {
      const value = calculate(scenario.category, values, {
        ...inputs,
        [primary.key]: shock,
      });
      return {
        shock,
        value: value.reason || !finite(value.modeled) ? null : value.modeled,
        ratio: value.reason ? null : value.afterRatio,
        impactPct: value.reason ? null : value.impactPct,
        reason: value.reason || null,
      };
    });
    rows.push({
      ...identity,
      ...result,
      unit: "USD",
      period: { ...checked[0].point.period },
      metricLabel: scenario.metricLabel,
      ratioLabel: scenario.ratioLabel,
      ratioUnit: scenario.ratioUnit,
      impactLabel: scenario.impactLabel,
      ratioChange:
        finite(result.beforeRatio) && finite(result.afterRatio)
          ? result.afterRatio - result.beforeRatio
          : null,
      enteredLoss: result.baseline >= 0 && result.modeled < 0,
      alreadyNegative: result.baseline < 0,
      recovered: result.baseline < 0 && result.modeled >= 0,
      evidence,
      sensitivity,
      sensitivityLabel: primary.label,
      sensitivityUnit: primary.unit,
      stale: company.status === "stale" || company.cache?.status === "stale",
      notes:
        scenario.category === "balance" && !result.noncashCapacityVerified
          ? [
              "Compatible reported cash is unavailable; the noncash asset-loss ceiling cannot be verified.",
            ]
          : [],
    });
  }
  rows.sort(
    (a, b) =>
      (a.afterRatio ?? Infinity) - (b.afterRatio ?? Infinity) ||
      a.ticker.localeCompare(b.ticker),
  );
  const sumWeight = (collection) =>
    weighted ? collection.reduce((sum, item) => sum + item.weightPct, 0) : null;
  return {
    scenario,
    inputs,
    errors,
    rows,
    exclusions,
    coverage: {
      includedCount: selected.length,
      eligibleCount,
      modeledCount: rows.length,
      excludedCount: exclusions.length,
      unavailableCount: exclusions.filter((item) => item.applicable).length,
      notApplicableCount: exclusions.filter((item) => !item.applicable).length,
      unresolvedCount: report?.unresolvedCount || 0,
      weighted,
      coveredWeightPct: sumWeight(rows),
      excludedWeightPct: sumWeight(exclusions),
      allocationLabel: weighted
        ? report.label || "Reviewed allocation"
        : "Company counts; weights not required",
    },
    summary: {
      medianImpactPct: median(rows.map((row) => row.impactPct)),
      medianBeforeRatio: median(rows.map((row) => row.beforeRatio)),
      medianAfterRatio: median(rows.map((row) => row.afterRatio)),
      enteredLossCount: rows.filter((row) => row.enteredLoss).length,
      alreadyNegativeCount: rows.filter((row) => row.alreadyNegative).length,
      negativeAfterCount: rows.filter((row) => row.modeled < 0).length,
      recoveredCount: rows.filter((row) => row.recovered).length,
      impactMeasuredCount: rows.filter((row) => finite(row.impactPct)).length,
      ratioMeasuredCount: rows.filter((row) => finite(row.afterRatio)).length,
      enteredLossWeightPct: sumWeight(rows.filter((row) => row.enteredLoss)),
      periodCount: new Set(rows.map((row) => portfolioPeriodKey(row.period)))
        .size,
    },
    assumptions: [
      "Illustrative, editable assumptions applied independently to each company's captured SEC financial baseline. Not a forecast, historical stress test, stock-price return, or probability estimate.",
      "Company results and company-count summaries do not require portfolio weights. Reviewed, complete investment weights annotate coverage only; company dollar impacts are never summed as portfolio profit or loss.",
      ...methodNotes[scenario.category],
      "Each company uses its own full reporting period. The median summarizes the available companies, which may have different fiscal calendars; it is not a synchronized or weighted portfolio result.",
      "CFTC market-wide positioning can motivate research into a filing-linked market. It does not set these assumptions or establish a company's hedge, price sensitivity, or earnings response.",
    ],
  };
}
